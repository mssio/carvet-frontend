// One-off converter: reads the pinned mockup's JS data files (.mockup/) and writes JSON + TS modules.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import vm from "node:vm";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const js = (f) => resolve(root, ".mockup/assets/js", f);

function load(file) {
  const window = {};
  vm.runInNewContext(readFileSync(js(file), "utf8"), { window, module: undefined });
  return window;
}

mkdirSync(resolve(root, "app/data"), { recursive: true });
mkdirSync(resolve(root, "app/components"), { recursive: true });
mkdirSync(resolve(root, "public/img"), { recursive: true });

const stats = load("stats.js").CARVET_STATS;
const cars = load("cars.js").CARVET_CARS;
const icons = load("icons.js").CARVET_ICONS;
if (!stats || !cars || !icons) throw new Error("Failed to load mockup data");

writeFileSync(resolve(root, "app/data/stats.json"), JSON.stringify(stats));
writeFileSync(resolve(root, "app/data/cars.json"), JSON.stringify(cars));

const names = Object.keys(icons).sort();
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n");
writeFileSync(
  resolve(root, "app/components/icons.ts"),
  `// GENERATED by scripts/convert-mockup-data.mjs from lucide-static 0.460.0 (ISC) via the mockup. Do not edit.
export const ICONS = {
${body}
} as const;

export type IconName = keyof typeof ICONS;
`,
);

copyFileSync(resolve(root, ".mockup/assets/img/logo.svg"), resolve(root, "public/logo.svg"));
for (const f of ["car-sedan", "car-suv", "car-pickup", "car-van"]) {
  copyFileSync(resolve(root, `.mockup/assets/img/${f}.svg`), resolve(root, `public/img/${f}.svg`));
}
console.log(`stats records=${stats.kpis.records}, cars=${cars.length}, icons=${names.length}`);
